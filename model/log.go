func GetAllLogs(logType int, startTimestamp int64, endTimestamp int64, modelName string, username string, tokenName string, startIdx int, num int, channel int, group string, requestId string, upstreamRequestId string) (logs []*Log, total int64, err error) {
	var tx *gorm.DB
	if logType == LogTypeUnknown {
		tx = LOG_DB
	} else {
		tx = LOG_DB.Where("logs.type = ?", logType)
	}

	if tx, err = applyExplicitLogTextFilter(tx, "logs.model_name", modelName); err != nil {
		return nil, 0, err
	}
	if tx, err = applyExplicitLogTextFilter(tx, "logs.username", username); err != nil {
		return nil, 0, err
	}
	if tokenName != "" {
		tx = tx.Where("logs.token_name = ?", tokenName)
	}
	if requestId != "" {
		tx = tx.Where("logs.request_id = ?", requestId)
	}
	if upstreamRequestId != "" {
		tx = tx.Where("logs.upstream_request_id = ?", upstreamRequestId)
	}
	if startTimestamp != 0 {
		tx = tx.Where("logs.created_at >= ?", startTimestamp)
	}
	if endTimestamp != 0 {
		tx = tx.Where("logs.created_at <= ?", endTimestamp)
	}
	if channel != 0 {
		tx = tx.Where("logs.channel_id = ?", channel)
	}
	if group != "" {
		tx = tx.Where("logs."+logGroupCol+" = ?", group)
	}
	err = tx.Model(&Log{}).Count(&total).Error
	if err != nil {
		return nil, 0, err
	}
	order := "logs.created_at desc, logs.id desc"
	if common.UsingLogDatabase(common.DatabaseTypeClickHouse) {
		order = clickHouseLogOrder("logs.")
	}
	err = tx.Order(order).Limit(num).Offset(startIdx).Find(&logs).Error
	if err != nil {
		return nil, 0, err
	}
	if common.UsingLogDatabase(common.DatabaseTypeClickHouse) {
		assignDisplayLogIds(logs, startIdx)
	}

	channelIds := types.NewSet[int]()
	for _, log := range logs {
		if log.ChannelId != 0 {
			channelIds.Add(log.ChannelId)
		}
	}

	if channelIds.Len() > 0 {
		var channels []struct {
			Id   int    `gorm:"column:id"`
			Name string `gorm:"column:name"`
		}
		if common.MemoryCacheEnabled {
			// Cache get channel
			for _, channelId := range channelIds.Items() {
				if cacheChannel, err := CacheGetChannel(channelId); err == nil {
					channels = append(channels, struct {
						Id   int    `gorm:"column:id"`
						Name string `gorm:"column:name"`
					}{
						Id:   channelId,
						Name: cacheChannel.Name,
					})
				}
			}
		} else {
			// Bulk query channels from DB
			if err = DB.Table("channels").Select("id, name").Where("id IN ?", channelIds.Items()).Find(&channels).Error; err != nil {
				return logs, total, err
			}
		}
		channelMap := make(map[int]string, len(channels))
		for _, channel := range channels {
			channelMap[channel.Id] = channel.Name
		}
		for i := range logs {
			logs[i].ChannelName = channelMap[logs[i].ChannelId]
		}
	}

	return logs, total, err
}

// ExportLogTypes are the log types included in an admin billing export:
// successful consume rows (type 2) and error rows (type 5).
var ExportLogTypes = []int{LogTypeConsume, LogTypeError}

// GetLogsForExport returns a single keyset page of logs for the admin billing
// export, filtered by time window, username list, and type IN (consume, error).
// Rows are ordered by (created_at, id) ascending; pass the last row's
// (createdAt, id) as the cursor to fetch the next page. The first call should
// pass lastCreatedAt=0, lastId=0. This avoids OFFSET so large exports stay fast
// and memory-flat across SQLite/MySQL/PostgreSQL.
func GetLogsForExport(startTimestamp int64, endTimestamp int64, usernames []string, lastCreatedAt int64, lastId int, limit int) ([]*Log, error) {
	if len(usernames) == 0 {
		return nil, errors.New("usernames is required")
	}
	if limit <= 0 {
		limit = 1000
	}
	tx := LOG_DB.Where("logs.type IN ?", ExportLogTypes).
		Where("logs.username IN ?", usernames)
	if startTimestamp != 0 {
		tx = tx.Where("logs.created_at >= ?", startTimestamp)
	}
	if endTimestamp != 0 {
		tx = tx.Where("logs.created_at <= ?", endTimestamp)
	}
	// Keyset cursor: (created_at, id) strictly greater than the last row.
	if lastCreatedAt != 0 || lastId != 0 {
		tx = tx.Where("logs.created_at > ? OR (logs.created_at = ? AND logs.id > ?)", lastCreatedAt, lastCreatedAt, lastId)
	}
	var logs []*Log
	err := tx.Order("logs.created_at asc, logs.id asc").Limit(limit).Find(&logs).Error
	if err != nil {
		return nil, err
	}
	return logs, nil
}

const logSearchCountLimit = 10000

func GetUserLogs(userId int, logType int, startTimestamp int64, endTimestamp int64, modelName string, tokenName string, startIdx int, num int, group string, requestId string, upstreamRequestId string) (logs []*Log, total int64, err error) {
	var tx *gorm.DB
	if logType == LogTypeUnknown {
		tx = LOG_DB.Where("logs.user_id = ?", userId)
	} else {
		tx = LOG_DB.Where("logs.user_id = ? and logs.type = ?", userId, logType)
	}

	if tx, err = applyExplicitLogTextFilter(tx, "logs.model_name", modelName); err != nil {
		return nil, 0, err
	}
	if tokenName != "" {
		tx = tx.Where("logs.token_name = ?", tokenName)
	}
	if requestId != "" {
		tx = tx.Where("logs.request_id = ?", requestId)
	}
	if upstreamRequestId != "" {
		tx = tx.Where("logs.upstream_request_id = ?", upstreamRequestId)
	}
	if startTimestamp != 0 {
		tx = tx.Where("logs.created_at >= ?", startTimestamp)
	}
	if endTimestamp != 0 {
		tx = tx.Where("logs.created_at <= ?", endTimestamp)
	}
	if group != "" {
		tx = tx.Where("logs."+logGroupCol+" = ?", group)
	}
	err = tx.Model(&Log{}).Limit(logSearchCountLimit).Count(&total).Error
	if err != nil {
		common.SysError("failed to count user logs: " + err.Error())
		return nil, 0, errors.New("查询日志失败")
	}
	order := "logs.id desc"
	if common.UsingLogDatabase(common.DatabaseTypeClickHouse) {
		order = clickHouseLogOrder("logs.")
	}
	err = tx.Order(order).Limit(num).Offset(startIdx).Find(&logs).Error
	if err != nil {
		common.SysError("failed to search user logs: " + err.Error())
		return nil, 0, errors.New("查询日志失败")
	}

	formatUserLogs(logs, startIdx)
	return logs, total, err
}

type Stat struct {
	Quota int `json:"quota"`
	Rpm   int `json:"rpm"`
	Tpm   int `json:"tpm"`
	// TotalInputTokens 与 CacheTokens 用于缓存命中率(命中率 = CacheTokens / TotalInputTokens),
	// 统计口径与 Quota 一致:按筛选时间区间 + 其它筛选、仅消费日志(type=2)。
	// TotalInputTokens 是“按厂商语义归一后的总输入 token”,不是 prompt_tokens 列本身:
	// Claude(usage_semantic=anthropic)的 prompt_tokens 只含非缓存输入,cache 与之互斥,
	// 故其总输入 = prompt_tokens + cache_tokens + cache_creation_tokens;OpenAI/Gemini 等
	// 的 prompt_tokens 已把缓存计入其中,故总输入 = prompt_tokens。若不归一,筛选到 Claude
	// 模型时 cache_tokens 远大于 prompt_tokens,比值恒 >100% 被封顶为假的 100%。
	TotalInputTokens int `json:"total_input_tokens"`
	CacheTokens      int `json:"cache_tokens"`
	// SuccessCount / ErrorCount 用于请求成功率(成功率 = SuccessCount / (SuccessCount + ErrorCount)),
	// 统计口径:按筛选时间区间 + 其它筛选,但忽略类型筛选(强制 type IN (2,5))。
	SuccessCount int `json:"success_count"`
	ErrorCount   int `json:"error_count"`
}

// logStatJSONIntRowExpr 返回按日志库方言从 other JSON 文本中提取单行某整数字段的 SQL 片段,
// 缺失/非法/空值一律降级为 0(而非 NULL),以便安全参与逐行算术。other 为 TEXT 列,相关字段
// 由后端以整数写入(GenerateTextOtherInfo / GenerateClaudeOtherInfo)。
//   - MySQL/SQLite:用 JSON_VALID/json_valid 守卫,非法 JSON 记 0。
//   - ClickHouse:JSONExtractInt 对非法/缺失输入本身返回 0。
//   - PostgreSQL:PG < 16 无跨版本可用的 JSON 合法性判定,且 other::jsonb 对任何非法非空文本
//     会直接抛错中断整条查询。故不做 JSON 解析,改用正则从文本按 top-level "field":N 提取整数;
//     非法/缺失均匹配失败,用 COALESCE 兜底为 0。位数限制在 9 位内,保证 ::int 不溢出。
func logStatJSONIntRowExpr(field string) string {
	switch {
	case common.UsingLogDatabase(common.DatabaseTypePostgreSQL):
		return fmt.Sprintf(`COALESCE((substring(other from '"%s"[[:space:]]*:[[:space:]]*(-?[0-9]{1,9})'))::int, 0)`, field)
	case common.UsingLogDatabase(common.DatabaseTypeMySQL):
		return fmt.Sprintf("(CASE WHEN JSON_VALID(other) THEN COALESCE(CAST(JSON_EXTRACT(other, '$.%s') AS SIGNED), 0) ELSE 0 END)", field)
	case common.UsingLogDatabase(common.DatabaseTypeClickHouse):
		return fmt.Sprintf("JSONExtractInt(other, '%s')", field)
	default: // SQLite
		return fmt.Sprintf("(CASE WHEN json_valid(other) THEN COALESCE(json_extract(other, '$.%s'), 0) ELSE 0 END)", field)
	}
}

// logStatIsAnthropicRowExpr 返回判定单行是否为 Claude/Anthropic 计费语义的 SQL 布尔片段。
// 写入端在 Claude 原生语义分支为 other 打上标记 "usage_semantic":"anthropic"(text_quota.go)。
// 该标记是区分“cache 与 prompt 互斥(Claude)”与“cache 已含于 prompt(OpenAI/Gemini)”的唯一
// 可靠依据,故用文本 LIKE 匹配即可,无需按方言解析 JSON。
func logStatIsAnthropicRowExpr() string {
	return `(other LIKE '%"usage_semantic":"anthropic"%')`
}

// logStatCacheTokensExpr 返回按筛选累加 cache_tokens(缓存命中率分子)的 SQL 片段。
func logStatCacheTokensExpr() string {
	return "COALESCE(SUM(" + logStatJSONIntRowExpr("cache_tokens") + "), 0) cache_tokens"
}

// logStatTotalInputTokensExpr 返回按厂商语义归一后的“总输入 token”累加片段(缓存命中率分母)。
// 逐行判定:Anthropic 行的 prompt_tokens 只含非缓存输入,与 cache/cache_creation 互斥,故总输入
// 需三者相加;其余厂商 prompt_tokens 已包含缓存,直接取列值。这样 SUM(cache) / SUM(total_input)
// 对两类语义都不会 >100%,历史行也一并被纠正。
func logStatTotalInputTokensExpr() string {
	return fmt.Sprintf(
		"COALESCE(SUM(CASE WHEN %s THEN prompt_tokens + %s + %s ELSE prompt_tokens END), 0) total_input_tokens",
		logStatIsAnthropicRowExpr(),
		logStatJSONIntRowExpr("cache_tokens"),
		logStatJSONIntRowExpr("cache_creation_tokens"),
	)
}

// applyLogStatCommonFilters 施加三条统计查询共用的筛选(用户名/令牌名/模型名/渠道/分组)。
// 时间区间与日志类型因各查询口径不同,由调用方分别追加。
func applyLogStatCommonFilters(tx *gorm.DB, modelName, username, tokenName string, channel int, group string) (*gorm.DB, error) {
	var err error
	if tx, err = applyExplicitLogTextFilter(tx, "username", username); err != nil {
		return nil, err
	}
	if tokenName != "" {
		tx = tx.Where("token_name = ?", tokenName)
	}
	if tx, err = applyExplicitLogTextFilter(tx, "model_name", modelName); err != nil {
		return nil, err
	}
	if channel != 0 {
		tx = tx.Where("channel_id = ?", channel)
	}
	if group != "" {
		tx = tx.Where(logGroupCol+" = ?", group)
	}
	return tx, nil
}

func SumUsedQuota(logType int, startTimestamp int64, endTimestamp int64, modelName string, username string, tokenName string, channel int, group string) (stat Stat, err error) {
	// 用量/缓存查询:按时间区间 + 其它筛选,仅消费日志(type=2)。
	// prompt_tokens 与 cache_tokens 累加用于缓存命中率。
	usageQuery := LOG_DB.Table("logs").
		Select("COALESCE(sum(quota), 0) quota, " + logStatTotalInputTokensExpr() + ", " + logStatCacheTokensExpr())
	// rpm/tpm 查询:实时口径,忽略时间区间,只看最近 60 秒。
	rpmTpmQuery := LOG_DB.Table("logs").
		Select("count(*) rpm, COALESCE(sum(prompt_tokens), 0) + COALESCE(sum(completion_tokens), 0) tpm")
	// 成功率查询:按时间区间 + 其它筛选,但忽略类型筛选,统计成功(type=2)与失败(type=5)计数。
	successQuery := LOG_DB.Table("logs").Select(fmt.Sprintf(
		"COALESCE(SUM(CASE WHEN type = %d THEN 1 ELSE 0 END), 0) success_count, "+
			"COALESCE(SUM(CASE WHEN type = %d THEN 1 ELSE 0 END), 0) error_count",
		LogTypeConsume, LogTypeError))

	if usageQuery, err = applyLogStatCommonFilters(usageQuery, modelName, username, tokenName, channel, group); err != nil {
		return stat, err
	}
	if rpmTpmQuery, err = applyLogStatCommonFilters(rpmTpmQuery, modelName, username, tokenName, channel, group); err != nil {
		return stat, err
	}
	if successQuery, err = applyLogStatCommonFilters(successQuery, modelName, username, tokenName, channel, group); err != nil {
		return stat, err
	}

	// 时间区间:用量与成功率跟随筛选;rpm/tpm 固定最近 60 秒。
	if startTimestamp != 0 {
		usageQuery = usageQuery.Where("created_at >= ?", startTimestamp)
		successQuery = successQuery.Where("created_at >= ?", startTimestamp)
	}
	if endTimestamp != 0 {
		usageQuery = usageQuery.Where("created_at <= ?", endTimestamp)
		successQuery = successQuery.Where("created_at <= ?", endTimestamp)
	}
	rpmTpmQuery = rpmTpmQuery.Where("created_at >= ?", time.Now().Add(-60*time.Second).Unix())

	// 日志类型:用量/rpm/tpm 仅消费;成功率跨消费与错误两类。
	usageQuery = usageQuery.Where("type = ?", LogTypeConsume)
	rpmTpmQuery = rpmTpmQuery.Where("type = ?", LogTypeConsume)
	successQuery = successQuery.Where("type IN ?", []int{LogTypeConsume, LogTypeError})

	if err := usageQuery.Scan(&stat).Error; err != nil {
		common.SysError("failed to query log stat: " + err.Error())
		return stat, errors.New("查询统计数据失败")
	}
	if err := rpmTpmQuery.Scan(&stat).Error; err != nil {
		common.SysError("failed to query rpm/tpm stat: " + err.Error())
		return stat, errors.New("查询统计数据失败")
	}
	// 成功率需要成功(type=2)与失败(type=5)两类计数才有意义。消费日志写入受
	// LogConsumeEnabled 控制,而错误日志不受控;开关关闭时分子恒为 0 会得到误导性的 0%。
	// 此时跳过成功率查询,让计数保持 0,由前端渲染为 “-”(不可用)而非虚假的 0%。
	if common.LogConsumeEnabled {
		if err := successQuery.Scan(&stat).Error; err != nil {
			common.SysError("failed to query success rate stat: " + err.Error())
			return stat, errors.New("查询统计数据失败")
		}
	}

	return stat, nil
}

func SumUsedToken(logType int, startTimestamp int64, endTimestamp int64, modelName string, username string, tokenName string) (token int) {
	tx := LOG_DB.Table("logs").Select("COALESCE(sum(prompt_tokens), 0) + COALESCE(sum(completion_tokens), 0)")
	if username != "" {
		tx = tx.Where("username = ?", username)
	}
	if tokenName != "" {
		tx = tx.Where("token_name = ?", tokenName)
	}
	if startTimestamp != 0 {
		tx = tx.Where("created_at >= ?", startTimestamp)
	}
	if endTimestamp != 0 {
		tx = tx.Where("created_at <= ?", endTimestamp)
	}
	if modelName != "" {
		tx = tx.Where("model_name = ?", modelName)
	}
	tx.Where("type = ?", LogTypeConsume).Scan(&token)
	return token
}

func CountOldLog(ctx context.Context, targetTimestamp int64) (int64, error) {
	var total int64
	if err := LOG_DB.WithContext(ctx).Model(&Log{}).Where("created_at < ?", targetTimestamp).Count(&total).Error; err != nil {
		return 0, err
	}
	return total, nil
}

func DeleteOldLogBatch(ctx context.Context, targetTimestamp int64, limit int) (int64, error) {
	if limit <= 0 {
		limit = 100
	}
	if nil != ctx.Err() {
		return 0, ctx.Err()
	}

	if common.UsingLogDatabase(common.DatabaseTypeClickHouse) {
		// ClickHouse DELETE is a heavy mutation that rewrites data parts, so
		// per-batch mutations would be pathologically slow. Remove all matching
		// rows in a single synchronous mutation regardless of limit; the reported
		// count lets the caller's progress loop complete in one pass.
		total, err := CountOldLog(ctx, targetTimestamp)
		if err != nil {
			return 0, err
		}
		if total == 0 {
			return 0, nil
		}
		if err := LOG_DB.WithContext(ctx).Exec(
			"ALTER TABLE logs DELETE WHERE created_at < ? SETTINGS mutations_sync = 1",
			targetTimestamp,
		).Error; err != nil {
			return 0, err
		}
		return total, nil
	}

	result := LOG_DB.WithContext(ctx).Where("created_at < ?", targetTimestamp).Limit(limit).Delete(&Log{})
	if nil != result.Error {
		return 0, result.Error
	}
	return result.RowsAffected, nil
}

func DeleteOldLog(ctx context.Context, targetTimestamp int64, limit int) (int64, error) {
	if limit <= 0 {
		limit = 100
	}

	var total int64 = 0

	for {
		if nil != ctx.Err() {
			return total, ctx.Err()
		}

		rowsAffected, err := DeleteOldLogBatch(ctx, targetTimestamp, limit)
		if nil != err {
			return total, err
		}

		total += rowsAffected

		if rowsAffected < int64(limit) {
			break
		}
	}

	return total, nil
}
